-- Esquema versionado (Oracle). Valores decimais ficam em VARCHAR2 para manter a aritmética exata (RNF-02).
-- Vigência: VIG_INI/VIG_FIM em texto ISO (AAAA-MM-DD); VIG_FIM nulo = em vigor.
CREATE TABLE ALIQUOTA_TRANSICAO (
  ANO NUMBER(4) NOT NULL,
  CBS_PCT VARCHAR2(20) NOT NULL,
  IBS_PCT VARCHAR2(20) NOT NULL,
  ICMS_ISS_VIGENTE_PCT NUMBER(3) NOT NULL,
  PIS_COFINS_EXTINTO NUMBER(1) NOT NULL,
  ANO_TESTE NUMBER(1) NOT NULL,
  FONTE VARCHAR2(400) NOT NULL,
  VIG_INI VARCHAR2(10) NOT NULL,
  VIG_FIM VARCHAR2(10),
  CONSTRAINT PK_ALIQUOTA_TRANSICAO PRIMARY KEY (ANO, VIG_INI)
);

CREATE TABLE SIMPLES_ANEXO_FAIXA (
  ANEXO VARCHAR2(3) NOT NULL,
  FAIXA NUMBER(2) NOT NULL,
  RBT12_ATE VARCHAR2(20) NOT NULL,
  ALIQ_NOMINAL VARCHAR2(20) NOT NULL,
  PARC_DEDUZIR VARCHAR2(20) NOT NULL,
  VIG_INI VARCHAR2(10) NOT NULL,
  VIG_FIM VARCHAR2(10),
  CONSTRAINT PK_SIMPLES_ANEXO_FAIXA PRIMARY KEY (ANEXO, FAIXA, VIG_INI)
);

CREATE TABLE SIMPLES_REPARTICAO (
  ANEXO VARCHAR2(3) NOT NULL,
  FAIXA NUMBER(2) NOT NULL,
  TRIBUTO VARCHAR2(10) NOT NULL,
  PCT VARCHAR2(20) NOT NULL,
  VIG_INI VARCHAR2(10) NOT NULL,
  VIG_FIM VARCHAR2(10),
  CONSTRAINT PK_SIMPLES_REPARTICAO PRIMARY KEY (ANEXO, FAIXA, TRIBUTO, VIG_INI)
);

CREATE TABLE ATIVIDADE_CNAE (
  CNAE VARCHAR2(9) NOT NULL,
  DESCRICAO VARCHAR2(400) NOT NULL,
  NATUREZA VARCHAR2(10) NOT NULL,
  ANEXO_SEM_FATOR_R VARCHAR2(3),
  USA_FATOR_R NUMBER(1) NOT NULL,
  PRESUNCAO_IRPJ VARCHAR2(20) NOT NULL,
  PRESUNCAO_CSLL VARCHAR2(20) NOT NULL,
  ORDEM NUMBER(4) NOT NULL,
  CONSTRAINT PK_ATIVIDADE_CNAE PRIMARY KEY (CNAE)
);

CREATE TABLE REGIME_PARAMETRO (
  REGIME VARCHAR2(30) NOT NULL,
  CHAVE VARCHAR2(40) NOT NULL,
  VALOR VARCHAR2(40) NOT NULL,
  FONTE VARCHAR2(400) NOT NULL,
  VIG_INI VARCHAR2(10) NOT NULL,
  VIG_FIM VARCHAR2(10),
  CONSTRAINT PK_REGIME_PARAMETRO PRIMARY KEY (REGIME, CHAVE, VIG_INI)
);
