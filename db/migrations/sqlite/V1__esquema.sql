-- Esquema versionado (SQLite). Valores decimais ficam em TEXT para manter a aritmética exata (RNF-02).
-- Vigência: VIG_INI/VIG_FIM em texto ISO (AAAA-MM-DD); VIG_FIM nulo = em vigor.
CREATE TABLE ALIQUOTA_TRANSICAO (
  ANO INTEGER NOT NULL,
  CBS_PCT TEXT NOT NULL,
  IBS_PCT TEXT NOT NULL,
  ICMS_ISS_VIGENTE_PCT INTEGER NOT NULL,
  PIS_COFINS_EXTINTO INTEGER NOT NULL,
  ANO_TESTE INTEGER NOT NULL,
  FONTE TEXT NOT NULL,
  VIG_INI TEXT NOT NULL,
  VIG_FIM TEXT,
  PRIMARY KEY (ANO, VIG_INI)
);

CREATE TABLE SIMPLES_ANEXO_FAIXA (
  ANEXO TEXT NOT NULL,
  FAIXA INTEGER NOT NULL,
  RBT12_ATE TEXT NOT NULL,
  ALIQ_NOMINAL TEXT NOT NULL,
  PARC_DEDUZIR TEXT NOT NULL,
  VIG_INI TEXT NOT NULL,
  VIG_FIM TEXT,
  PRIMARY KEY (ANEXO, FAIXA, VIG_INI)
);

CREATE TABLE SIMPLES_REPARTICAO (
  ANEXO TEXT NOT NULL,
  FAIXA INTEGER NOT NULL,
  TRIBUTO TEXT NOT NULL,
  PCT TEXT NOT NULL,
  VIG_INI TEXT NOT NULL,
  VIG_FIM TEXT,
  PRIMARY KEY (ANEXO, FAIXA, TRIBUTO, VIG_INI)
);

CREATE TABLE ATIVIDADE_CNAE (
  CNAE TEXT NOT NULL PRIMARY KEY,
  DESCRICAO TEXT NOT NULL,
  NATUREZA TEXT NOT NULL,
  ANEXO_SEM_FATOR_R TEXT,
  USA_FATOR_R INTEGER NOT NULL,
  PRESUNCAO_IRPJ TEXT NOT NULL,
  PRESUNCAO_CSLL TEXT NOT NULL,
  ORDEM INTEGER NOT NULL
);

CREATE TABLE REGIME_PARAMETRO (
  REGIME TEXT NOT NULL,
  CHAVE TEXT NOT NULL,
  VALOR TEXT NOT NULL,
  FONTE TEXT NOT NULL,
  VIG_INI TEXT NOT NULL,
  VIG_FIM TEXT,
  PRIMARY KEY (REGIME, CHAVE, VIG_INI)
);
